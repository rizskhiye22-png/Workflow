export function textWidth(str) {
  return String(str).length * 4 - 1;
}

/** Gambar teks pixel 3x5. px(x,y,w,h,color) adalah fungsi isi kotak. */
export function drawText(px, str, x, y, color) {
  let cx = x;
  for (const ch of String(str).toUpperCase()) {
    const g = F[ch] || F['?'];
    for (let i = 0; i < 15; i++) if (g[i] === '1') px(cx + (i % 3), y + Math.floor(i / 3), 1, 1, color);
    cx += 4;
  }
}

