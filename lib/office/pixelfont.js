export function drawIcon(px, name, x, y, color) {
  const g = ICON[name];
  if (!g) return;
  for (let r = 0; r < 5; r++) for (let c = 0; c < 5; c++) if (g[r][c] === '#') px(x + c, y + r, 1, 1, color);
}
